-- 1. TABEL PROFIL GURU & MATA PELAJARAN
create table if not exists public.teachers (
  id uuid references auth.users on delete cascade primary key,
  email text not null,
  nama_guru text not null,
  mapel text not null,
  nip text default '',
  role text default 'guru', -- 'guru' atau 'superadmin'
  status text default 'pending', -- 'pending', 'approved', 'rejected'
  created_at timestamptz default now()
);
alter table public.teachers add column if not exists status text default 'pending';

-- 2. TABEL MATERI PEMBELAJARAN
create table if not exists public.materials (
  id bigint generated by default as identity primary key,
  teacher_id uuid references public.teachers(id) on delete cascade,
  mapel text not null,
  kelas text not null, -- contoh: "VII.1" atau "Semua Kelas VII"
  judul text not null,
  konten text not null, -- teks rangkuman / materi belajar
  lampiran_url text default '',
  link_video text default '',
  created_at timestamptz default now()
);

-- 3. TABEL PENUGASAN (ASSIGNMENTS)
create table if not exists public.assignments (
  id bigint generated by default as identity primary key,
  teacher_id uuid references public.teachers(id) on delete cascade,
  mapel text not null,
  kelas text not null,
  judul_tugas text not null,
  deskripsi text not null,
  deadline timestamptz,
  rubrik_ai text default '', -- panduan kunci/kriteria untuk AI auto-koreksi
  created_at timestamptz default now()
);

-- 4. UPDATE TABEL PENGUMPULAN TUGAS (FILES) DENGAN SISTEM PENILAIAN LMS
alter table public.files add column if not exists teacher_id uuid;
alter table public.files add column if not exists mapel text default 'Informatika';
alter table public.files add column if not exists assignment_id bigint;
alter table public.files add column if not exists nilai integer; -- 0 sampai 100
alter table public.files add column if not exists catatan_guru text default '';
alter table public.files add column if not exists ai_feedback text default '';
alter table public.files add column if not exists status_koreksi text default 'belum_dikoreksi'; -- 'belum_dikoreksi', 'sudah_dikoreksi'
alter table public.files add column if not exists link_url text default '';
alter table public.files add column if not exists tipe text default 'file';

-- 5. TABEL UJIAN / KUIS ONLINE
create table if not exists public.quizzes (
  id bigint generated by default as identity primary key,
  teacher_id uuid references public.teachers(id) on delete cascade,
  mapel text not null,
  kelas text not null,
  judul_kuis text not null,
  petunjuk text default '',
  durasi_menit integer default 45,
  status text default 'aktif', -- 'draft', 'aktif', 'selesai'
  created_at timestamptz default now()
);

-- 6. TABEL BUTIR SOAL UJIAN (PILIHAN GANDA & ESAI)
create table if not exists public.quiz_questions (
  id bigint generated by default as identity primary key,
  quiz_id bigint references public.quizzes(id) on delete cascade,
  nomor integer not null,
  tipe text not null, -- 'pg' (pilihan ganda) atau 'esai'
  pertanyaan text not null,
  opsi_a text default '',
  opsi_b text default '',
  opsi_c text default '',
  opsi_d text default '',
  kunci_pg text default '', -- 'A', 'B', 'C', atau 'D'
  rubrik_esai text default '', -- rubrik kunci evaluasi untuk AI
  bobot integer default 10
);

-- 7. TABEL HASIL PENGERJAAN UJIAN SISWA
create table if not exists public.quiz_submissions (
  id bigint generated by default as identity primary key,
  quiz_id bigint references public.quizzes(id) on delete cascade,
  nama_siswa text not null,
  kelas text not null,
  jawaban_siswa jsonb not null default '{}'::jsonb,
  skor_pg integer default 0,
  skor_esai integer default 0,
  total_nilai integer default 0,
  ai_feedback jsonb default '{}'::jsonb,
  catatan_guru text default '',
  status_koreksi text default 'selesai',
  created_at timestamptz default now()
);

-- ====================================================================
-- ROW LEVEL SECURITY (RLS) & KEBIJAKAN AKSES
-- ====================================================================
alter table public.teachers enable row level security;
alter table public.materials enable row level security;
alter table public.assignments enable row level security;
alter table public.quizzes enable row level security;
alter table public.quiz_questions enable row level security;
alter table public.quiz_submissions enable row level security;

